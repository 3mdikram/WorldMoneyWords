    private static final Map<String, String> CODES = createCodes();

    private SupportedCountries() {}

    private static Map<String, String> createCodes() {
        Map<String, String> codes = new HashMap<>(ALPHA2_TO_ALPHA3);
        for (String alpha3 : ALPHA2_TO_ALPHA3.values()) codes.put(alpha3, alpha3);
        return codes;
    }

    static String normalize(String input) {
        if (input == null) throw new IllegalArgumentException("Country code is required");
        String normalized = CODES.get(input.trim().toUpperCase());
        if (normalized == null) throw new IllegalArgumentException("Unknown supported Alpha-2 or Alpha-3 country code: " + input);
        return normalized;
    }
